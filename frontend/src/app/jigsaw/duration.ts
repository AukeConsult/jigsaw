/** A time played as a clock: `12:34`, or `1:02:03` when it is an hour or more (the milliseconds are rounded down to whole seconds). */
export function clockOf(ms: number | undefined | null): string {
  const total = Math.max(0, Math.floor((ms ?? 0) / 1000));
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const two = (n: number) => String(n).padStart(2, '0');
  return h > 0 ? `${h}:${two(m)}:${two(s)}` : `${m}:${two(s)}`;
}
